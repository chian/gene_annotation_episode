class ResourceAcquisitionCredit:
    def credit_kind(self, role):
        if role != 'results':
            raise ValueError('fixed_resource_role_required')
        if 'results' not in ROLES:
            raise ValueError('unknown_resource_episode_role')
        return 'operational'

    def credit_view(self, context, receiver_selection):
        if context.role != 'results':
            raise ValueError('fixed_resource_context_required')
        return self.services.bound_role_credit(context, receiver_selection)
