"""One MetaCATS analysis through the BV-BRC application service (the ``MetaCATS`` application) of a held graded alignment of
the target with the sequences of product candidates, as plain library functions that the actions of the ``bvbrc_metacats``
episode call. The five actions, their checks, the estimate gate, the credit and the ledger are the shared ``bvbrc_job_child``;
this module is the binding of the ``MetaCATS`` application to it (``APPLICATION``) and what is specific:

* THE REQUIREMENT: the alignment is a held data-product row of kind ``multiple_sequence_alignment`` (``records/data_products``:
  ``require_product``); the commission and the launch are refused, with the product's problem code, unless it is held and
  of that kind. The commission names the row; the alignment, the sequence of each candidate and the target's row are read from
  the held alignment source (provider ``bvbrc_msa``) whose alignment artifact the row labels, and its graded sheet;
* the groups: code, not the model, builds them (``bvbrc_metacats_analysis.build_groups``): one group per product candidate of
  the alignment (at least two sequences), its members that candidate's reference sequences; THE TARGET IS IN NO GROUP. The
  service makes a sequence of no group a group of its own (established live), so the alignment the job takes is the held one
  without the target's row, the same columns (``derived_alignment``), written with the group file under the job's own folder;
* the extract: the service's chi-square table is fetched and graded in the same unit (``bvbrc_metacats_analysis.grade``): the
  sheet, a source of provider ``bvbrc_metacats``, a ``reference`` record and a ``comparison`` observation per candidate group
  and the report labelled as an ``alignment_position_report`` data product (generated by the job's handoff, used: the group
  file, derived from the alignment product, its place in the BV-BRC workspace in ``locations``).

The reuse key of the report is computed from what is known before the launch: ``used`` = the group file's artifact (its
reference is the digest of its bytes) and ``settings`` = the application, the p-value and the candidates (sorted)."""
import hashlib
import json

from gene_annotation_episode.episodic_workflow.episode_support.grading.sequence_homology_evidence.tool_grading_artifacts import (
    retain_tool_grading, source_tool_grading_entries)
from gene_annotation_episode.episodic_workflow.episode_support.records.data_products import (
    find_reusable, products, record_product, require_product)
from gene_annotation_episode.episodic_workflow.episode_support.tools.sequence_homology_evidence.tools import (
    measurements, number, ref)
from gene_annotation_episode.episodic_workflow.episode_support.tools.similarity_search.sequence_homology_evidence.bvbrc_job_child import (
    JobApplication, check_resource_and_continuation)
from gene_annotation_episode.episodic_workflow.episode_support.tools.similarity_search.sequence_homology_evidence.bvbrc_metacats_analysis import (
    ALIGNMENT_FILE, CHISQ_FILE, GROUP_FILE, MC_FILE, MINIMUM_GROUPS, MINIMUM_GROUP_SIZE, P_VALUES, build_groups,
    derived_alignment, grade, group_file_text, parse_alignment)
from gene_annotation_episode.episodic_workflow.episode_support.tools.similarity_search.sequence_homology_evidence.database_blast_search import (
    _choose, _failed)

CHILD = 'bvbrc_metacats'
PROVIDER = 'bvbrc_metacats'
ALIGNMENT_PROVIDER = 'bvbrc_msa'
ALIGNMENT_KIND = 'multiple_sequence_alignment'
PRODUCT_KIND = 'alignment_position_report'
REQUEST_FIELDS = ('p_value', 'resource_id')


def settings_of(products, p_value):
    """The settings of the report (closed JSON): the reuse key and the product's settings."""
    return {'application': 'MetaCATS', 'p_value': p_value, 'groups': sorted(products)}


# -- the plan --------------------------------------------------------------------------------------------------------
def alignment_source(reader, row):
    """The held alignment source (provider ``bvbrc_msa``) whose alignment artifact the product row labels, with its sheet."""
    (source,) = [item for item in reader.list('source')
                 if item['provider'] == ALIGNMENT_PROVIDER and item['artifact_ref'] == row['artifact_ref']]
    (entry,) = source_tool_grading_entries(reader, source['id'])
    return source, entry['grading']['sheet']


def plan(reader, alignment_ref):
    """What the job is built from, read from the held alignment product row ``alignment_ref`` and the sheet of its source (the
    records the child returned; the alignment artifact is NOT opened here, so the head can call this): ``{'target_id',
    'groups', 'source_ref', 'query_ref', 'alignment_artifact', 'columns'}``. The groups are ``build_groups`` over the sheet's
    reference sequences (each named as the alignment names it, with its candidate); the alignment holds every sequence the
    sheet lists (the grading checked it)."""
    row, problem = require_product(reader, alignment_ref, ALIGNMENT_KIND)
    if problem is not None:
        raise ValueError(problem)
    source, sheet = alignment_source(reader, row)
    target_id = sheet['alignment']['target_name']
    members = {item['name']: item['candidate'] for item in sheet['references']}
    groups = build_groups(members, target_id, list(members))
    return {'target_id': target_id, 'groups': groups, 'source_ref': source['id'],
            'query_ref': source['operand_refs'][0], 'alignment_artifact': row['artifact_ref'],
            'columns': sheet['alignment']['columns']}


def alignment_rows(reader, planned):
    """The rows of the held alignment (read in the child, which holds the artifact)."""
    return parse_alignment(reader.get_artifact(planned['alignment_artifact']).decode('ascii'))


def held_alignments(reader):
    """The alignments the episode holds that MetaCATS can take: one row per held data product of kind
    ``multiple_sequence_alignment`` whose groups number at least ``MINIMUM_GROUPS`` (each of at least
    ``MINIMUM_GROUP_SIZE`` sequences): ``{'alignment_ref', 'query_ref', 'candidates'}`` (the candidates: each group's product
    and size)."""
    found = []
    for row in products(reader, ALIGNMENT_KIND):
        planned = plan(reader, row['id'])
        if len(planned['groups']) >= MINIMUM_GROUPS:
            found.append({'alignment_ref': row['id'], 'query_ref': planned['query_ref'],
                          'source_ref': planned['source_ref'], 'groups_ref': group_artifact_ref(planned),
                          'candidates': [{'name': group['product'], 'size': len(group['ids'])}
                                         for group in planned['groups']]})
    return found


def group_artifact_ref(planned):
    """The reference of the group file's artifact: a Store artifact's reference is the digest of its bytes."""
    return 'artifact_' + hashlib.sha256(group_file_text(planned['groups']).encode()).hexdigest()


def reusable_report(reader, alignment_ref, p_value):
    """The held report of exactly this alignment's groups and p-value, or ``None``."""
    planned = plan(reader, alignment_ref)
    return find_reusable(reader, PRODUCT_KIND, [group_artifact_ref(planned)],
                         settings_of([group['product'] for group in planned['groups']], p_value))


def planned_size(planned):
    """The size of the job the plan gives: the sequences in groups, the groups and the alignment's columns."""
    return {'sequences': sum(len(group['ids']) for group in planned['groups']), 'groups': len(planned['groups']),
            'columns': planned['columns']}


# -- the binding -----------------------------------------------------------------------------------------------------
def field_problems(request, commission):
    return []


def requirement_problems(reader, commission):
    """The problem the commission's alignment has as a data product (the requirement): ``data_product_not_held`` or
    ``data_product_kind_mismatch``, with the field."""
    _, problem = require_product(reader, commission['alignment_ref'], ALIGNMENT_KIND)
    return [] if problem is None else [_choose('alignment_ref', problem, kind=ALIGNMENT_KIND)]


def prepare(ctx, request, commission):
    """The job of one launch: the groups and the derived alignment built by code from the held alignment, kept as artifacts
    and given as the job's two inputs."""
    planned = plan(ctx.store, commission['alignment_ref'])
    alignment_ref = ctx.store.artifact(derived_alignment(alignment_rows(ctx.store, planned), planned['groups']).encode(
        'ascii'), 'text/plain')
    groups_ref = ctx.store.artifact(group_file_text(planned['groups']).encode('ascii'), 'text/tab-separated-values')
    size = planned_size(planned)
    return {'job': {'application': 'MetaCATS', 'p_value': request['p_value'], 'alignment_file': ALIGNMENT_FILE,
                    'group_file': GROUP_FILE},
            'inputs': {ALIGNMENT_FILE: alignment_ref, GROUP_FILE: groups_ref},
            'job_facts': {'sequences': size['sequences'], 'groups': size['groups'], 'columns': size['columns']}}


def describe_identity(reader, handoff):
    """The controlled identity of a held MetaCATS job: its p-value and the group file it was given."""
    return {'p_value': handoff['detail']['estimates']['request']['p_value'],
            'groups_ref': handoff['detail']['input_refs'][GROUP_FILE]}


def extract(ctx, handoff_ref, request, commission):
    """Fetch the chi-square table of the finished job and grade it in the same unit; keep, through custody: the grading
    artifact, a source of provider ``bvbrc_metacats`` over the table, a reference record and a comparison observation per
    candidate group and the report as an ``alignment_position_report`` data product. A fault of the grading is returned once
    as ``grading_refused``."""
    store = ctx.store
    fetched = ctx.services['job_access'].fetch(ctx, handoff_ref, names=[CHISQ_FILE, MC_FILE])
    if fetched['status'] != 'completed':
        return {**_failed(fetched['failure']['code'], False), 'closure_ref': None}
    (result_ref,) = [item['ref'] for item in fetched['results'] if item['name'] == CHISQ_FILE]
    planned = plan(store, commission['alignment_ref'])
    try:
        grading = {'sheet': grade(alignment_rows(store, planned), planned['groups'], planned['target_id'],
                                  store.get_artifact(result_ref).decode('ascii'), p_value=request['p_value'])}
    except ValueError as error:
        return {**_failed('grading_refused', False, reason=str(error)), 'closure_ref': fetched['closure_ref']}
    sheet = grading['sheet']
    (path,) = [item['workspace_path'] for item in json.loads(store.get_artifact(fetched['reply_ref']))['catalog']
               if item['name'] == CHISQ_FILE]
    target_ref = planned['query_ref']
    with store.transaction():
        grading_ref = retain_tool_grading(store, provider=PROVIDER, native_artifact_ref=result_ref, grading=grading)
        source = store.put('source', {
            'provider': PROVIDER, 'accession': None, 'uri': None, 'artifact_ref': result_ref, 'text_ref': None,
            'request_ref': None, 'version': 'p%g' % request['p_value'], 'retrieved_at': None,
            'auxiliary_artifact_refs': [grading_ref], 'operand_refs': [target_ref]}, origin='tool')
        references, observations = [], []
        for group, value in zip(sheet['groups'], sheet['values'] or [None] * len(sheet['groups'])):
            reference = store.put('reference', {
                'reference_type': 'protein', 'source_ref': source['id'], 'accession': group['label'], 'label': group['product'],
                'sequence_ref': None, 'molecule': 'protein', 'length': None, 'term_refs': [], 'context_refs': []},
                origin='external')
            references.append(reference['id'])
            if value is not None:
                observations.append(store.put('observation', {
                    'kind': 'comparison', 'subject_refs': [target_ref], 'source_subject_refs': [reference['id']],
                    'source_ref': source['id'], 'anchor': None,
                    'measurements': measurements(reference_ref=ref(reference['id']),
                                                 identity_fraction=number(value['value']),
                                                 count=number(sheet['significant_count']),
                                                 row_count=number(group['size'])),
                    'dependencies': [target_ref, reference['id']]}, origin='tool')['id'])
        product = record_product(
            store, artifact_ref=result_ref, kind=PRODUCT_KIND, generated_by=handoff_ref,
            used=[group_artifact_ref(planned)], derived_from=[commission['alignment_ref']],
            settings=settings_of([group['product'] for group in sheet['groups']], request['p_value']),
            locations=[{'service': 'bvbrc_workspace', 'path': path}])
    refs = [source['id'], grading_ref, product['id'], *references, *observations]
    return {'status': 'completed', 'failure_code': None, 'retryable': False, 'closure_ref': fetched['closure_ref'],
            'graded_refs': refs, 'record_refs': [*refs, fetched['closure_ref']], 'product_ref': product['id'],
            'group_count': sheet['group_count'], 'sequence_count': sheet['sequence_count'],
            'column_count': sheet['columns'], 'significant_count': sheet['significant_count']}


def graded_rows(reader):
    """The graded analyses the episode holds: one row per held source of provider ``bvbrc_metacats`` with the sheet's facts."""
    rows = []
    for source in reader.list('source'):
        if source['provider'] != PROVIDER:
            continue
        (entry,) = source_tool_grading_entries(reader, source['id'])
        sheet = entry['grading']['sheet']
        rows.append({'source_ref': source['id'], 'grading_ref': entry['artifact_ref'], 'p_value': sheet['p_value'],
                     'group_count': sheet['group_count'], 'sequence_count': sheet['sequence_count'],
                     'column_count': sheet['columns'], 'significant_count': sheet['significant_count'],
                     'values': sheet['values']})
    return rows


def check_commission(request, *, reader, options, resources, jobs, commissioned):
    """The things to fix in the head's commission of this child (``request``: ``query_ref``, ``alignment_ref``, ``p_value``,
    ``resource_id``, ``until``). ``options`` is ``held_alignments``; ``jobs`` the head's held MetaCATS jobs
    (``bvbrc_job_child.held_jobs``); ``commissioned`` the (alignment, p-value) of the earlier commissions. The conditions: the
    alignment is a held data product of kind ``multiple_sequence_alignment`` (the requirement) with at least two groups, of
    the target; the p-value is one of the set; the resource a bound BV-BRC service; an outstanding job of this commission is
    continued (``until`` ``extracted``) and another one blocks it; a report already held (or already commissioned and not
    held) is not commissioned again."""
    problems = requirement_problems(reader, request)
    option = [item for item in options if item['alignment_ref'] == request['alignment_ref']]
    if not problems and not option:
        problems.append(_choose('alignment_ref', 'alignment_has_fewer_than_two_groups_of_two_sequences',
                                choose_from=[item['alignment_ref'] for item in options]))
    elif option and option[0]['query_ref'] != request['query_ref']:
        problems.append(_choose('query_ref', 'query_is_not_the_alignments_target', choose_from=[option[0]['query_ref']]))
    if request['p_value'] not in P_VALUES:
        problems.append(_choose('p_value', 'p_value_is_not_offered', choose_from=list(P_VALUES)))
    same = lambda job: (job['request']['p_value'] == request['p_value'] and job['resource_id'] == request['resource_id']
                        and job['identity']['groups_ref'] == group_artifact_ref(plan(reader, request['alignment_ref'])))
    if not problems:
        problems.extend(check_resource_and_continuation(request, resources=resources, jobs=jobs, same=same))
        reusable = reusable_report(reader, request['alignment_ref'], request['p_value'])
        if reusable is not None:
            problems.append(_choose('p_value', PRODUCT_KIND + '_already_held', row=reusable['id']))
        if (request['alignment_ref'], request['p_value']) in commissioned and not any(
                job['outstanding'] and same(job) for job in jobs):
            problems.append(_choose('p_value', 'analysis_already_commissioned'))
    return problems


APPLICATION = JobApplication(
    application='MetaCATS', child=CHILD, service='bvbrc_metacats', provider=PROVIDER, product_kind=PRODUCT_KIND,
    request_fields=REQUEST_FIELDS, estimate_fields=('p_value',),
    field_schemas={'p_value': {'type': 'number', 'enum': list(P_VALUES)}, 'resource_id': {'type': 'string', 'minLength': 1}},
    size_field='sequences', kind=lambda fields: 'MetaCATS:protein', field_problems=field_problems, prepare=prepare,
    extract=extract, describe_identity=describe_identity)

