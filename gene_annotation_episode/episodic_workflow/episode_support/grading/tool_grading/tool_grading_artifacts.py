"""Custody of complete tool grading outputs beside their original artifacts.

This module stores and resolves supplied results. It performs no scientific
calculation, acquisition, job selection, observation publication or credit
assignment. Graders remain ordinary pure functions in their own modules.
"""
from __future__ import annotations

from collections.abc import Mapping
import json

from gene_annotation_episode.domain import ContractError, canonical
from gene_annotation_episode.episodic_workflow.episode_support.records.data_products import record_product


SCHEMA = "tool_grading_artifact"
MEDIA_TYPE = "application/vnd.gene-annotation.tool-grading+json"
GRADING_KIND = "tool_grading_sheet"


def retain_tool_grading(store, *, provider: str, native_artifact_ref: str,
                        grading: dict) -> str:
    """Retain a full numerical sheet/calculation result without another record."""
    if not isinstance(provider, str) or not provider or not isinstance(grading, Mapping):
        raise ContractError("tool_grading_provider_and_result_required")
    if store.get(native_artifact_ref).get("record_type") != "artifact":
        raise ContractError("tool_grading_native_artifact_required")
    body = {"schema": SCHEMA, "provider": provider, "native_artifact_ref": native_artifact_ref, "grading": dict(grading)}
    return store.artifact(canonical(body), MEDIA_TYPE)


def record_grading_product(store, *, grading_ref: str, grading: Mapping, provider: str, source_ref: str,
                           used, derived_from=()) -> dict:
    """Label the retained grading ``grading_ref`` (``retain_tool_grading``) as a ``tool_grading_sheet`` data product and
    return its row: generated by the unit's source record over the graded artifact (``source_ref``), made from the
    artifacts the grader read (``used``: the graded artifact first) and derived from their data-product rows
    (``derived_from``), with the provider and the sheet's schema as settings (the same artifacts graded by the same grader
    give the same reuse key)."""
    return record_product(store, artifact_ref=grading_ref, kind=GRADING_KIND, generated_by=source_ref, used=list(used),
                          derived_from=list(derived_from),
                          settings={"provider": provider, "sheet_schema": grading["sheet"]["schema"]})


def source_tool_grading_entries(store, source_ref: str) -> list[dict]:
    """Resolve exact retained artifact addresses and their validated grading.

    The caller owns receipt/scope qualification before calling this host helper.
    Neither a source handle nor this function grants a child access to new data.
    """
    source = store.get(source_ref)
    if source.get("record_type") != "source":
        raise ContractError("tool_grading_source_required")
    results = []
    for reference in source.get("auxiliary_artifact_refs", ()):
        artifact = store.get(reference)
        if artifact.get("media_type") != MEDIA_TYPE:
            continue
        try:
            body = json.loads(store.get_artifact(reference))
            if (not isinstance(body, dict) or set(body) != {"schema", "provider", "native_artifact_ref", "grading"}
                    or body["schema"] != SCHEMA
                    or body["provider"] != source["provider"]
                    or body["native_artifact_ref"] != source["artifact_ref"]
                    or not isinstance(body["grading"], dict)):
                raise ContractError("tool_grading_source_custody_mismatch")
            canonical(body)
        except (ValueError, TypeError, KeyError, IndexError) as error:
            if isinstance(error, ContractError):
                raise
            raise ContractError("invalid_tool_grading_artifact") from error
        results.append({"artifact_ref": reference, "grading": body["grading"]})
    return results


def held_grading_sheets(records, provider: str) -> list[tuple[str, dict]]:
    """``[(source reference, sheet)]`` of the held sources of ``provider`` among ``records`` (a custody reader), in the order held;
    each source carries exactly one retained grading."""
    found = []
    for source in records.list("source"):
        if source["provider"] != provider:
            continue
        (entry,) = source_tool_grading_entries(records, source["id"])
        found.append((source["id"], entry["grading"]["sheet"]))
    return found


__all__ = ["retain_tool_grading", "record_grading_product", "source_tool_grading_entries", "held_grading_sheets", "SCHEMA", "MEDIA_TYPE", "GRADING_KIND"]
