_StrictValidator = validators.extend(Draft202012Validator,
    type_checker=Draft202012Validator.TYPE_CHECKER.redefine(
        "integer", lambda checker, value: type(value) is int).redefine(
        "number", lambda checker, value: type(value) in {int, float}))


def _finite_json_copy(value: object) -> Any:
    """Copy JSON without scalar coercion, nonfinite numbers or non-JSON objects."""
    if value is None or type(value) in {str, bool, int}:
        if type(value) is str:
            try:
                value.encode("utf-8")
            except UnicodeEncodeError as error:
                raise ValueError("genomic_overlap_invalid_unicode") from error
        return value
    if type(value) is float and math.isfinite(value):
        return value
    if type(value) is list:
        return [_finite_json_copy(item) for item in value]
    if type(value) is dict and all(type(key) is str for key in value):
        return {_finite_json_copy(key): _finite_json_copy(item) for key, item in value.items()}
    raise ValueError("genomic_overlap_finite_json_required")


def genomic_overlap_schema(record_name: str) -> dict:
    """Return a detached schema for one fixed, declared data definition."""
    if type(record_name) is not str or record_name not in GENOMIC_OVERLAP_DEFINITIONS:
        raise ValueError("genomic_overlap_unknown_record")
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$ref": "#/$defs/" + record_name,
            "$defs": deepcopy(GENOMIC_OVERLAP_DEFINITIONS)}


def validate_genomic_overlap_record(record_name: str, value: object) -> dict:
    """Validate structure and scalar types; never acquire or interpret data."""
    schema = genomic_overlap_schema(record_name)
    # Keep the strict integer checker on every reference traversal.
    schema.pop("$schema")
    result = _finite_json_copy(value)
    error = next(_StrictValidator(schema, format_checker=FormatChecker()).iter_errors(result), None)
    if error is not None:
        path = "/" + "/".join(str(item) for item in error.absolute_path)
        raise ValueError(f"genomic_overlap_schema:{record_name}:{path}:{error.validator}")
    return result


def canonical_genomic_overlap_sheet_sha256(sheet: dict) -> str:
    """Hash the exact structurally valid sheet; do not recalculate its contents."""
    checked = validate_genomic_overlap_record("Sheet", sheet)
    raw = json.dumps(checked, sort_keys=True, separators=(",", ":"),
                     ensure_ascii=False, allow_nan=False).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()
