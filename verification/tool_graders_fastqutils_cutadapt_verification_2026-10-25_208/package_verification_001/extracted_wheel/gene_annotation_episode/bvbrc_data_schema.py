_TYPE_CHECKER = _Draft202012Validator.TYPE_CHECKER.redefine_many({
    "integer": lambda _checker, value: type(value) is int,
    "number": lambda _checker, value: type(value) in (int, float),
    "boolean": lambda _checker, value: type(value) is bool,
})
_Validator = _extend(_Draft202012Validator, type_checker=_TYPE_CHECKER)


def _references(value):
    if isinstance(value, dict):
        if "$ref" in value:
            yield value["$ref"].removeprefix("#/$defs/")
        for child in value.values():
            yield from _references(child)
    elif isinstance(value, list):
        for child in value:
            yield from _references(child)


def schema(name: str) -> dict:
    """Return a detached frozen record schema with all transitive definitions."""
    if type(name) is not str or name not in _DEFINITIONS:
        raise ValueError("bvbrc_unknown_schema")
    needed = {name}
    pending = [name]
    while pending:
        for referenced in _references(_DEFINITIONS[pending.pop()]):
            if referenced not in needed:
                needed.add(referenced)
                pending.append(referenced)
    return {"$schema": "https://json-schema.org/draft/2020-12/schema",
            "$ref": "#/$defs/" + name,
            "$defs": {key: _deepcopy(value) for key, value in _DEFINITIONS.items()
                      if key in needed}}


def _finite_copy(value):
    active = set()

    def copy(item):
        kind = type(item)
        if item is None or kind in (str, int, bool):
            return item
        if kind is float:
            if not _math.isfinite(item):
                raise ValueError("bvbrc_nonfinite_number")
            return item
        if kind not in (dict, list) or id(item) in active:
            raise ValueError("bvbrc_non_json_value")
        active.add(id(item))
        try:
            if kind is list:
                return [copy(child) for child in item]
            if any(type(key) is not str for key in item):
                raise ValueError("bvbrc_non_json_key")
            return {key: copy(child) for key, child in item.items()}
        finally:
            active.remove(id(item))

    try:
        return copy(value)
    except RecursionError as error:
        raise ValueError("bvbrc_non_json_value") from error


@_lru_cache(maxsize=None)
def _validator(name):
    return _Validator(schema(name))


def validate(name: str, value: dict) -> dict:
    """Validate plain finite JSON and frozen shape; return a detached copy.

    Native integers must be Python/JSON integers, never integral floats or
    booleans. This generic layer does not confer host custody or validate the
    scientific relationships owned by individual extractors.
    """
    if type(name) is not str or name not in _DEFINITIONS:
        raise ValueError("bvbrc_unknown_schema")
    result = _finite_copy(value)
    try:
        _validator(name).validate(result)
    except _ValidationError as error:
        location = "/" + "/".join(str(part) for part in error.absolute_path)
        raise ValueError("bvbrc_schema_invalid:" + name + ":" + location) from error
    return result


def fact_schemas() -> dict:
    """Return detached, fully expanded closed schemas for the six fact sources."""
    def expand(value):
        if isinstance(value, dict):
            if "$ref" in value:
                return expand(_DEFINITIONS[value["$ref"].removeprefix("#/$defs/")])
            return {key: expand(child) for key, child in value.items()}
        if isinstance(value, list):
            return [expand(child) for child in value]
        return value
    return expand(_FACT_SCHEMAS)


def json_digest(value) -> str:
    """Hash finite plain JSON with the BV-BRC UTF-8 canonical convention.

    This is for BV-BRC-specific value digests only. It does not redefine any
    existing host source, assignment, selector or admission identity function.
    """
    copied = _finite_copy(value)
    try:
        encoded = _json.dumps(copied, sort_keys=True, separators=(",", ":"),
                              ensure_ascii=False, allow_nan=False).encode("utf-8")
    except (ValueError, UnicodeError) as error:
        raise ValueError("bvbrc_invalid_digest_value") from error
    return _hashlib.sha256(encoded).hexdigest()
