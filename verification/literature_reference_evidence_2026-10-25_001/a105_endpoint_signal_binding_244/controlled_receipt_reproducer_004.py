"""CONTROLLED fixtures only: explicit root reads, no endpoint binding claimed.

This reproduces generic operation/admission behavior. The endpoint operation is
not implemented yet, so the root is given an equivalent derived source handle
as controlled initial custody; this is not proof of an actual typed endpoint
child return. Every provider input/output here is explicitly scripted fixture
data generated by this file. No real provider data or public paper is opened.
"""
import asyncio
from functools import partial
import json
from pathlib import Path
import sys

ROOT=Path(__file__).resolve().parents[3]
OWN=Path(__file__).resolve().parent
sys.path[:0]=[str(ROOT),str(ROOT/'tests')]
from gene_annotation_episode.investigation_progress import ScientificFindingProgress, FindingProgressPolicy
from gene_annotation_episode.domain import canonical
from gene_annotation_episode.literature_episodes import LiteratureEpisodes
from gene_annotation_episode.runtime import run_workflow
from gene_annotation_episode.state import Store
from gene_annotation_episode.tools import ToolRegistry
from test_runtime import ScriptedProvider, FixtureController

def main():
    state=OWN/'controlled_reproducer_state_004'
    if state.exists():
        raise RuntimeError('Preserve original evidence: choose another state suffix for rerun')
    store=Store(state)
    manifest=state/'controlled-empty-manifest.json'
    manifest.write_text(json.dumps({'schema_version':1,'entries':[]}))
    store.create_problem(manifest_path=manifest)
    def source(raw,provider,parents=None):
        artifact=store.artifact(raw)
        row={'provider':provider,'accession':None,'uri':None,'artifact_ref':artifact,
            'text_ref':artifact,'request_ref':None,'version':'controlled_fixture_v1','retrieved_at':None}
        if parents is not None:row['parent_source_refs']=parents
        return store.put('source',row,origin='caller')['id']
    original=source(b'CONTROLLED ORIGINAL: source reading is a separately selected action.',
        'controlled_original_source_fixture')
    derived=source(canonical({'kind':'CONTROLLED_DERIVED_IMPLEMENTATION_RECEIPT',
        'admitted_component':'retained_fraction','admitted_conditional_value':0.625,
        'unrequested_coordinates':[617,619,631],'unrequested_covariance':[[641,0,0],[0,643,0],[0,0,647]]}).encode(),
        'controlled_derived_implementation_receipt_fixture',[original])
    alias=store.put('reference',{'reference_type':'assay','source_ref':original,
        'accession':'CONTROLLED_ALIAS_244','label':'CONTROLLED BROAD ALIAS: unrequested value 653',
        'sequence_ref':None,'molecule':None,'length':None,'term_refs':[],'context_refs':[]},origin='caller')['id']
    captured=[]
    def first(inputs):
        captured.append({'phase':'initial','child_report_count':len(inputs.get('child_reports',[])),
            'received_derived_source_only':True})
        return {'selection':{'kind':'tool','tool':'source.read','arguments':{
            'source_ref':derived,'representation':'original','offset':0,'limit':4096}},'report_update':{}}
    def second(inputs):
        prior=inputs['last_local_outcome']
        text=prior['result']['text']
        assert '617' in text and '647' in text and 'CONTROLLED_DERIVED' in text
        captured.append({'phase':'after_explicit_derived_read','status':prior['status'],
            'derived_payload_contains_unrequested_controlled_fixture_values':True})
        return {'selection':{'kind':'tool','tool':'source.read','arguments':{
            'source_ref':original,'representation':'original','offset':0,'limit':4096}},'report_update':{}}
    def third(inputs):
        prior=inputs['last_local_outcome']
        assert 'CONTROLLED ORIGINAL' in prior['result']['text']
        captured.append({'phase':'after_explicit_original_read','status':prior['status'],
            'original_source_read_remains_ordinary_allowed_action':True})
        return {'selection':{'kind':'tool','tool':'state.query','arguments':{'refs':[alias]}},'report_update':{}}
    commission={'selection':{'kind':'episode_child','role':'literature','assignment':{'version':'literature_assignment_v1','question_context_refs':[],'source_refs':[derived]},'goal':'Read explicitly selected controlled source windows.','scope':store.validate_scope(),'purpose':'Return controlled completion status only.','schema_json':json.dumps({'type':'object','properties':{'status':{'type':'string','enum':['fixture_complete']}},'required':['status'],'additionalProperties':False}),'initial_report_json':json.dumps({'status':'fixture_complete'})},'report_update':{}}
    provider=ScriptedProvider([commission,first,second,third])
    progress=ScientificFindingProgress(FindingProgressPolicy(1))
    try:
        asyncio.run(run_workflow(store,ToolRegistry(store),provider=provider,run_dir=OWN/'controlled_reproducer_run_004',
            controller_factory=lambda path,initial:FixtureController(str(path),initial,1 if len(path)==1 else 3),
            project_credit=progress,binding_definitions={"credit":progress.as_record()},initial_known_record_refs=[derived],
            episode_binding_factories=(partial(LiteratureEpisodes,rate_population=True,
                reference_parent_sources=[derived]),)))
        action_rows=list(store.db.execute('SELECT decision_index,action,result FROM runtime_actions ORDER BY decision_index'))
        selected=[]
        for row in action_rows:
            action=json.loads(row['action']);result=json.loads(row['result'])
            entry={'index':row['decision_index'],'tool':action.get('tool',action['kind']),'status':result['status']}
            if action.get('tool')=='state.query':
                entry['records']=[{'id':r['id'],'label':r.get('label')} for r in result['result']['records']]
            selected.append(entry)
        receipts=[dict(row) for row in store.db.execute('SELECT * FROM runtime_record_receipts')]
        output={'status':'controlled_generic_operation_reproducer_completed',
            'not_an_actual_endpoint_typed_delivery_test':True,
            'actual_model_execution':False,'private_provider_data_read':False,
            'initial_known_refs':[derived],'original_source_ref':original,'derived_source_ref':derived,
            'alias_ref':alias,'captured_controlled_provider_facts':captured,'selected_actions':selected,
            'runtime_observations':store.db.execute('SELECT count(*) FROM runtime_observations').fetchone()[0],
            'runtime_receipts':receipts}
        (OWN/'CONTROLLED_RECEIPT_REPRODUCER_004.json').write_text(json.dumps(output,indent=2)+'\n')
        print(json.dumps({'selected_actions':selected,'runtime_observations':output['runtime_observations'],
            'output':'CONTROLLED_RECEIPT_REPRODUCER_004.json'}))
    finally:
        store.close()

if __name__=='__main__':main()
