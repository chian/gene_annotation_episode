def test_schemas_keep_exact_native_row_shapes_and_reject_extra_analysis_fields():
    actual = components(model_reports(), parse_profile=PROFILE)
    window = project_native_peak_window(actual, run_keys=['chipseq'], row_window=dict(offset=0, limit=3))
    for kind, value in (('Components', actual), ('Window', window)):
        validator = Draft202012Validator(macs2_peak_schema(kind))
        validator.validate(value)
        malformed = deepcopy(value)
        malformed['scientific_confidence'] = 1
        assert not validator.is_valid(malformed)
    exposed = macs2_peak_schema('Window')
    exposed['$defs'].clear()
    Draft202012Validator(macs2_peak_schema('Window')).validate(window)


@pytest.mark.parametrize('defect', ['producer', 'role', 'run'])
def test_original_report_associations_are_qualified_without_reassigning_native_data(defect):
    inputs = model_reports()
    report = inputs['narrowpeaks'][0]
    if defect == 'producer':
        report['artifact']['producer_run_ref'] = 'different-producer'
    elif defect == 'role':
        inputs['callpeak_bindings'][0]['artifact_roles']['narrowpeak'] = 'different-output'
    else:
        report['callpeak_run_key'] = report['binding_key'] = 'different-run'
    before = deepcopy(inputs)
    actual = components(inputs, parse_profile=PROFILE)
    assert any(row['code'] == 'condition_binding_conflict' for row in actual['issues'])
    retained = next(row for row in actual['narrowpeaks'] if row['rows'])
    assert retained['rows'] == report['rows']
    assert retained['artifact'] == report['artifact']
    assert inputs == before


