def components(inputs, **options):
    return build_macs2_peak_components(**{key: inputs[key] for key in FIELDS}, **options)


def model_binding():
    binding = callpeak(2)
    binding.update(run_key='chipseq', condition_id='chip', sample_ids=['treatment'],
        treatment_input_refs=['treatment.bed'], supplied_control_sample_ids=['control'],
        supplied_control_input_refs=['control.bed'], selected_format='AUTO',
        selected_argv=['macs2', 'callpeak', '-t', 'treatment.bed', '-c', 'control.bed',
                       '-n', 'chip', '-g', '12010000', '-q', '0.05'])
    binding['selected_parameters'].update(genome_size_argument='12010000',
        effective_genome_size_bp=12010000, nomodel=False, shift_bp=0,
        extension_size_bp=200, store_bedgraph=False,
        small_local_window_bp=1000, large_local_window_bp=10000)
    binding['artifact_roles'].update(peaks_xls='chip_peaks.xls', narrowpeak='chip_peaks.narrowPeak',
        summits='chip_summits.bed', signal_track=None, background_track=None)
    return binding


def model_reports(*, rows=True, narrow_repeat=False, narrow_end=3190,
                  reported_format='AUTO', partial=False, binding=None):
    """Native-format examples, not measurements from a newly executed model."""
    binding = model_binding() if binding is None else binding
    header = (
        '# This file is generated by MACS version 2.2.9.1\n'
        '# Command line: callpeak -t treatment.bed -c control.bed -n chip -g 12010000 -q 0.05\n'
        '# name = chip\n'
        f'# format = {reported_format}\n'
        "# ChIP-seq file = ['treatment.bed']\n"
        "# control file = ['control.bed']\n"
        '# effective genome size = 1.20e+07\n'
        '# band width = 300\n# model fold = [5, 50]\n'
        '# qvalue cutoff = 5.00e-02\n'
        '# Larger dataset will be scaled towards smaller dataset.\n'
        '# Range for calculating regional lambda is: 1000 bps and 10000 bps\n'
        '# Broad region calling is off\n# Paired-End mode is off\n'
        '# tag size is determined as 50 bps\n'
        '# total tags in treatment: 12010\n'
        '# tags after filtering in treatment: 12010\n'
        '# maximum duplicate tags at the same position in treatment = 1\n'
        '# Redundant rate in treatment: 0.00\n'
        '# total tags in control: 12010\n'
        '# tags after filtering in control: 12010\n'
        '# maximum duplicate tags at the same position in control = 1\n'
        '# Redundant rate in control: 0.00\n# d = 199\n'
    ).encode()
    xls = header + XLS_HEADER
    narrow, summit = b'', b''
    if rows:
        xls += b'chrToy\t2910\t3190\t281\t3021\t100\t108.597\t23.3077\t104.594\tchip_peak_1\n'
        narrow = f'chrToy\t2909\t{narrow_end}\tchip_peak_1\t1045\t.\t23.3077\t108.597\t104.594\t111\n'.encode()
        if narrow_repeat:
            narrow += narrow
        summit = b'chrToy\t3020\t3021\tchip_peak_1\t104.594\n'
    reports = {}
    for key, role, fmt, parser, raw in (
        ('peaks_xls', 'peaks_xls', 'macs2_peaks_xls_narrow', parse_macs2_peaks_xls, xls),
        ('narrowpeaks', 'narrowpeak', 'macs2_narrowpeak10', parse_macs2_narrowpeak, narrow),
        ('summits', 'summits', 'macs2_summits_bed5', parse_macs2_summits_bed, summit),
    ):
        descriptor = artifact(raw, binding['artifact_roles'][role], fmt, binding['producer_ref'])
        if partial:
            descriptor['supplied_extent'] = 'partial'
        reports[key] = [parser(raw, artifact=descriptor, callpeak=binding, parse_profile=PROFILE)]
    return dict(reference=reference(), callpeak_bindings=[binding], **reports)


def test_retained_original_sheet_and_counts_are_literal_parity_oracles(monkeypatch):
    raw = ORIGINAL.read_bytes()
    assert len(raw) == 77830
    assert hashlib.sha256(raw).hexdigest() == '00591fc9b8b9bdb2e2f284500be17110bde582b5104677e8382a1f8d5e5179b3'
    retained = json.loads(raw)
    saved = retained['native_sheet']
    before = deepcopy(saved)
    def forbidden(*args, **kwargs):
        raise AssertionError('retained peak projection attempted acquisition or native execution')
    monkeypatch.setattr(socket, 'socket', forbidden)
    monkeypatch.setattr(subprocess, 'Popen', forbidden)
    actual = components(saved)
    for key in (*FIELDS, 'peak_links', 'reference_relation', 'data_status'):
        assert canonical(actual[key]) == canonical(saved[key])
    assert native_peak_counts(actual) == retained['original_calculations']['summary']['native_peak_counts']
    assert actual['issues'] == []
    assert saved == before
    assert actual['narrowpeaks'][1]['rows'][0]['display_score'] == 1045


