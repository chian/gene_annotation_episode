@pytest.mark.parametrize('defect', ['outside', 'unknown', 'alias'])
def test_explicit_reference_checks_preserve_original_native_chromosome_and_coordinates(defect):
    inputs = model_reports()
    if defect == 'outside':
        inputs['reference']['contigs'][0]['length_bp'] = 3000
    else:
        inputs['reference']['contigs'][0]['chromosome'] = 'canonicalToy'
        if defect == 'alias':
            inputs['reference']['aliases'] = [dict(reference_id='toy', source_chromosome='chrToy',
                target_chromosome='canonicalToy', source_refs=[])]
    actual = components(inputs, parse_profile=PROFILE)
    assert actual['narrowpeaks'][0]['rows'][0]['chromosome'] == 'chrToy'
    assert actual['narrowpeaks'][0]['rows'][0]['start0'] == 2909
    expected = 'coordinate_outside_reference' if defect == 'outside' else 'unknown_chromosome'
    found = [row for row in actual['issues'] if row['code'] == expected]
    if defect == 'alias':
        assert not found
    else:
        assert found and all(row['locations'] for row in found)


