def test_default_profile_keeps_its_existing_no_control_native_mode_requirement():
    inputs = model_reports()
    binding, raw_report = inputs['callpeak_bindings'][0], inputs['peaks_xls'][0]
    raw = b''.join((header['text'] + '\n').encode() for header in raw_report['headers'])
    raw += b'\t'.join(field.encode() for field in raw_report['rows'][0]['original_fields']) + b'\n'
    default = parse_macs2_peaks_xls(raw,
        artifact=artifact(raw, binding['artifact_roles']['peaks_xls'], 'macs2_peaks_xls_narrow', binding['producer_ref']),
        callpeak=binding)
    assert any(row['code'] == 'unsupported_mode' for row in default['issues'])
    assert default['rows'][0]['original_fields'] == raw_report['rows'][0]['original_fields']


